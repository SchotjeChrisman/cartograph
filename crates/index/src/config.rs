//! Skip and tag rules, with the defaults PLAN.md names. `.cartograph/config.toml` replaces any
//! list it mentions.
//!
//! Pattern forms: `dir/` matches a directory anywhere in the path, `*tail` and `head*` match the
//! start or end of the file name, anything else must equal the file name.

use graph::GraphDir;
use serde::{Deserialize, Serialize};

use crate::error::{Error, Result, io_error};

const CONFIG_FILE: &str = "config.toml";

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Config {
    /// Paths indexed but tagged `vendored`.
    pub vendored: Vec<String>,
    /// Paths indexed but tagged `generated`, besides files carrying a marker in their header.
    pub generated: Vec<String>,
    /// Lowercase phrases that mark a file as generated when found in its first lines.
    pub generated_markers: Vec<String>,
    /// Files that are never read or stored.
    pub secrets: Vec<String>,
}

#[derive(Deserialize, Default)]
#[serde(deny_unknown_fields)]
struct ConfigFile {
    vendored: Option<Vec<String>>,
    generated: Option<Vec<String>>,
    generated_markers: Option<Vec<String>>,
    secrets: Option<Vec<String>>,
}

fn strings(items: &[&str]) -> Vec<String> {
    items.iter().map(|item| item.to_string()).collect()
}

impl Default for Config {
    fn default() -> Self {
        Config {
            vendored: strings(&[
                "third_party/",
                "third-party/",
                "vendor/",
                "node_modules/",
                "*.min.js",
            ]),
            generated: strings(&["*.pb.h", "*.pb.cc", "*_generated.h", "*.generated.rs"]),
            generated_markers: strings(&[
                "@generated",
                "do not edit",
                "autogenerated",
                "auto-generated",
                "automatically generated",
                "generated by",
                "this file is generated",
            ]),
            secrets: strings(&[
                ".env",
                ".env.*",
                "*.pem",
                "*.key",
                "*.p12",
                "*.pfx",
                "*.jks",
                "*.keystore",
                "id_rsa*",
                "id_dsa*",
                "id_ecdsa*",
                "id_ed25519*",
                "credentials*",
                "*.secret",
                ".netrc",
                ".htpasswd",
            ]),
        }
    }
}

impl Config {
    /// Reads `.cartograph/config.toml` when it exists.
    pub fn load(dir: &GraphDir) -> Result<Self> {
        let path = dir.path().join(CONFIG_FILE);
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Ok(Config::default());
            }
            Err(error) => return Err(io_error(&path)(error)),
        };
        Self::from_toml(&text).map_err(|source| Error::Config { path, source })
    }

    pub fn from_toml(text: &str) -> std::result::Result<Self, toml::de::Error> {
        let file: ConfigFile = toml::from_str(text)?;
        let defaults = Config::default();
        Ok(Config {
            vendored: file.vendored.unwrap_or(defaults.vendored),
            generated: file.generated.unwrap_or(defaults.generated),
            generated_markers: file.generated_markers.unwrap_or(defaults.generated_markers),
            secrets: file.secrets.unwrap_or(defaults.secrets),
        })
    }
}

/// Whether `pattern` matches the root-relative `path`.
pub fn pattern_matches(pattern: &str, path: &str) -> bool {
    let name = path.rsplit('/').next().unwrap_or(path);
    if let Some(directory) = pattern.strip_suffix('/') {
        return format!("/{path}").contains(&format!("/{directory}/"));
    }
    if let Some(tail) = pattern.strip_prefix('*') {
        return name.ends_with(tail);
    }
    if let Some(head) = pattern.strip_suffix('*') {
        return name.starts_with(head);
    }
    name == pattern
}

/// The first pattern in `patterns` matching `path`.
pub fn first_match<'a>(patterns: &'a [String], path: &str) -> Option<&'a str> {
    patterns
        .iter()
        .map(String::as_str)
        .find(|pattern| pattern_matches(pattern, path))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_each_pattern_form() {
        assert!(pattern_matches("vendor/", "vendor/x.c"));
        assert!(pattern_matches("vendor/", "a/vendor/x.c"));
        assert!(!pattern_matches("vendor/", "a/myvendor/x.c"));
        assert!(pattern_matches("*.pem", "keys/a.pem"));
        assert!(pattern_matches(".env.*", "app/.env.local"));
        assert!(pattern_matches(".env", "app/.env"));
        assert!(!pattern_matches(".env", "app/dotenv"));
        assert!(pattern_matches("id_rsa*", "home/id_rsa.pub"));
    }

    #[test]
    fn config_file_replaces_only_the_lists_it_names() {
        let config = Config::from_toml("vendored = [\"extern/\"]").unwrap();
        assert_eq!(config.vendored, ["extern/"]);
        assert_eq!(config.secrets, Config::default().secrets);
    }
}
